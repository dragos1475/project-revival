"""Trace the LifeWatch logo (scripts/assets/lifewatch-logo.jpg) into SVG paths, one per animated part.

Writes src/components/logo-paths.ts (arc band, arrowhead, continents, leaf, microscope) and public/favicon.svg.
Usage: python3 scripts/trace_logo.py scripts/assets/lifewatch-logo.jpg
Needs numpy, scipy, scikit-image and Pillow.
"""
import json, sys
import numpy as np
from PIL import Image
from scipy import ndimage as ndi
from skimage import measure

SRC = sys.argv[1]
GREEN, GREY = "#7ED600", "#7C7C7C"
im = np.asarray(Image.open(SRC).convert("RGB")).astype(float)
r, g, b = im[..., 0], im[..., 1], im[..., 2]
H, W = r.shape
BG = 247.0

# Coverage (0..1) of each ink, from the distance to the light background, so edges stay anti-aliased.
green_cov = np.where((g - r > 5) & (g - b > 15), np.clip((BG - b) / BG, 0, 1), 0)
grey_cov = np.where((np.abs(g - r) < 14) & (np.abs(g - b) < 14) & (r < 240), np.clip((BG - r) / (BG - 124), 0, 1), 0)

yy, xx = np.mgrid[0:H, 0:W]

# Outer rim of the arrow: fit a circle to the left and bottom edge of the big green shape.
main = ndi.label(green_cov > 0.5)[0]
main = main == np.bincount(main.ravel())[1:].argmax() + 1
pts = [(np.nonzero(main[y])[0][0], y) for y in range(150, 800, 5) if main[y].any()]
pts += [(x, np.nonzero(main[:, x])[0][-1]) for x in range(120, 460, 5) if main[:, x].any()]


def fit_circle(p):
    p = np.asarray(p, float)
    a = np.c_[2 * p[:, 0], 2 * p[:, 1], np.ones(len(p))]
    x, y, c = np.linalg.lstsq(a, (p ** 2).sum(1), rcond=None)[0]
    return x, y, np.sqrt(c + x * x + y * y)


cx, cy, R = fit_circle(pts)
ang = np.degrees(np.arctan2(yy - cy, xx - cx))

# Inner edge of the tapered arrow band, sampled on rays where only the band reaches the rim.
inner = []
for a in list(range(88, 181, 4)) + list(range(-180, -159, 4)) + [-112, -108, -104, -100]:
    t, hit, last = np.radians(a), False, None
    for rr in np.arange(R + 4, 0, -0.25):
        x, y = int(round(cx + rr * np.cos(t))), int(round(cy + rr * np.sin(t)))
        if main[y, x]:
            hit, last = True, rr
        elif hit:
            break
    if last and last > 370:
        inner.append((cx + last * np.cos(t), cy + last * np.sin(t)))
icx, icy, iR = fit_circle(inner)

TAIL, HEAD_SPLIT = -97.0, 81.0  # band runs from the top (TAIL) anticlockwise to the arrowhead (HEAD_SPLIT)
leaf_box = (xx > 700) & (yy > 400) & (yy < 590)
head_box = (xx > 495) & (xx < 680) & (yy > 760) & (ang > 35) & (ang < 92)
arc_zone = ((np.hypot(xx - icx, yy - icy) > iR - 0.5) & ~((ang > TAIL) & (ang < 35))) | head_box
arrow = np.where(arc_zone & ~leaf_box, green_cov, 0)
head_sel = head_box & (ang < HEAD_SPLIT)
parts = {
    "band": np.where(~head_sel, arrow, 0),
    "head": np.where(head_sel, arrow, 0),
    "globe": np.where(~arc_zone & ~leaf_box, green_cov, 0),
    "leaf": np.where(leaf_box, green_cov, 0),
    "scope": grey_cov,
}

S = 4  # trace on a 4x upsampled, lightly blurred coverage map for smooth sub-pixel outlines


def trace(cov, tol):
    up = ndi.gaussian_filter(ndi.zoom(cov, S, order=1), 1.2)
    out = []
    for c in measure.find_contours(up, 0.5):
        c = measure.approximate_polygon(c, tolerance=tol * S)
        if len(c) < 4:
            continue
        ys, xs = c[:, 0] / S, c[:, 1] / S
        if 0.5 * abs(np.dot(xs, np.roll(ys, 1)) - np.dot(ys, np.roll(xs, 1))) < 6:
            continue
        out.append("M" + " ".join(f"{x:.1f} {y:.1f}".replace(".0 ", " ") for x, y in zip(xs, ys)).removesuffix(".0") + "Z")
    return "".join(out)


ink = np.maximum(green_cov, grey_cov) > 0.5
ys, xs = np.nonzero(ink)
pad = 6
box = [int(xs.min()) - pad, int(ys.min()) - pad, int(xs.max() - xs.min()) + 2 * pad, int(ys.max() - ys.min()) + 2 * pad]
paths = {k: trace(v, 0.5) for k, v in parts.items()}

ts = f"""// Generated by scripts/trace_logo.py from scripts/assets/lifewatch-logo.jpg. Do not edit by hand.
// Parts of the LifeWatch logo, split so each can be animated on its own.

export const LOGO_VIEWBOX = "{' '.join(map(str, box))}";
/** Centre and radius of the circle the arrow band follows. */
export const LOGO_ARC = {{ cx: {cx:.1f}, cy: {cy:.1f}, r: {R:.1f} }};
export const LOGO_PATHS = {json.dumps(paths, indent=2)} as const;
"""
open("src/components/logo-paths.ts", "w").write(ts)

fav = {k: trace(v, 1.2) for k, v in parts.items()}
green = "".join(fav[k] for k in ("band", "head", "globe", "leaf"))
open("public/favicon.svg", "w").write(
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{" ".join(map(str, box))}">'
    f'<path fill="{GREEN}" d="{green}"/><path fill="{GREY}" d="{fav["scope"]}"/></svg>\n'
)
print(f"arc centre ({cx:.1f}, {cy:.1f}) r={R:.1f}; inner ({icx:.1f}, {icy:.1f}) r={iR:.1f}; viewBox {box}")
print({k: len(v) for k, v in paths.items()}, "favicon", sum(len(v) for v in fav.values()))
